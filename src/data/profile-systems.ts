/**
 * Aluminium + metal-plastic (PVC) profile-system catalog.
 *
 * Powers the two hubs (/alyuminiievi-konstruktsii/, /metaloplastykovi-konstruktsii/)
 * and their child pages, rendered by src/components/profile/ProfileCategoryPage.astro.
 *
 * SOURCES (checked 2026-09-25)
 * - Assortment, system list, images: the previous Space Glass site
 *   vikna.space-glass.com.ua (the exact systems Space Glass already sells).
 * - Technical values (Uw/Uf/UD, EN 12207/12208/12210 classes, max sizes and
 *   sash weights, profile depths, glazing ranges): the manufacturer pages
 *   aluprof.com/en/product/{system}. PVC values (Aluplast IDEAL 8000,
 *   WDS 76 MD, Ultra 70) come from the old Space Glass site.
 * Texts are Space Glass's own wording. No prices are published by either
 * source, so none are shown — every page sends users to an individual quote.
 */

export type ProfileGroup = 'alu' | 'pvc' | 'mirror' | 'shower' | 'frameless';

export interface ProfileModel {
  id: string;
  name: string;
  brand?: string;
  /** Short label shown on the card image, e.g. "Розпашні вікна". */
  kind: string;
  blurb: string;
  /** Base name in /images/catalog/profile-systems/ ({image}-480|900.webp). */
  image?: string;
  imageAlt?: string;
  specs: [string, string][];
  features: string[];
  /** Indicative manufacturer price, e.g. "орієнтовно від 5 179 грн". */
  priceFrom?: string;
  priceNote?: string;
}

export interface ProfileCategory {
  slug: string;
  group: ProfileGroup;
  path: string;
  /** Short name for menus, cards and breadcrumbs. */
  name: string;
  h1: string;
  metaTitle: string;
  metaDescription: string;
  eyebrow: string;
  lead: string;
  cardNote: string;
  heroImage: string;
  heroAlt: string;
  introHeading: string;
  intro: string[];
  introSpec: [string, string][];
  catalogHeading: string;
  catalogIntro: string;
  models: ProfileModel[];
  compareColumns: string[];
  compareRows: string[][];
  useHeading: string;
  useIntro: string;
  uses: [string, string][];
  chooseHeading: string;
  chooseSteps: [string, string][];
  seoHeading: string;
  seo: string[];
  faq: [string, string][];
  related: [string, string][];
  ctaTitle: string;
  ctaText: string;
  /** Image folder for hero/model images; defaults to IMG_BASE. */
  imageBase?: string;
  /** Hero button / form select wording (defaults: систем / Система). */
  catalogButton?: string;
  optionsLabel?: string;
  /** Replaces the default "manufacturer specs" note under the catalog. */
  catalogNote?: string;
  /** Six process steps [title, note]; defaults to the profile-system flow. */
  process?: [string, string][];
  /** Optional "materials & quality" cards: [title, text, image base in imageBase]. */
  details?: { heading: string; intro: string; items: [string, string, string][] };
}


export const cityHubSlugs = ['kyiv', 'odesa', 'lviv'] as const;
export type CityHubSlug = (typeof cityHubSlugs)[number];

export const cityHubs: Record<Locale, Record<string, CityHub>> = {
  uk: { kyiv: kyivUk, odesa: odesaUk, lviv: lvivUk },
  ru: { kyiv: kyivRu, odesa: odesaRu, lviv: lvivRu }
};

export function getCityHub(slug: string, locale: Locale = 'uk'): CityHub {
  const hub = cityHubs[locale]?.[slug] ?? cityHubs.uk[slug];
  if (!hub) throw new Error(`Unknown city hub: ${slug} (${locale})`);
  return hub;
}

export type CityHubLocale = Locale;

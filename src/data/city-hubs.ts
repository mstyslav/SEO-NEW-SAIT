//   UA:  /city/kyiv/   /city/odesa/   /city/lviv/
//   RU:  /ru/city/kyiv/ /ru/city/odesa/ /ru/city/lviv/
//
// One shared template (src/components/pages/CityHubPage.astro) renders every
// page; all per-city, per-locale copy lives here. Kyiv is the approved MASTER —
// Odesa and Lviv follow its structure 1:1 with their own commercial content.
//
// Rules baked in here:
//  * only real, existing global URLs — no invented /city/{slug}/{service}/ routes;
//  * category cards come from the shared homepage category data, not a hand copy;
//  * project proof is pulled live from the `projects` content collection by the
//    real `city` field — never a hardcoded card list;
//  * stats/facts reuse the numbers already published on /rishennya/ and /about/;
//  * no invented office address, no invented service districts, no invented
//    testimonials or figures.

import type { Locale } from '../i18n/helpers';

export interface CityHubScenario {
  title: string;
  text: string;
  href: string;
}

export interface CityHubLink {
  label: string;
  href: string;
}

export interface CityHub {
  /** Route slug under /city/. */
  slug: string;
  /** City name, nominative — used in eyebrows and chips. */
  cityNominative: string;
  /** City name, locative ("у Києві" / "в Киеве") — used mid-sentence. */
  cityLocative: string;
  /**
   * Value of the `city` field in src/content/projects/*.json used to pull the
   * local project proof block. Always the Ukrainian enum value — the projects
   * collection is uk-only; RU display text comes from the *Ru fields on each
   * project via ProjectCard.
   */
  projectCity: 'Київ' | 'Львів' | 'Одеса';

  meta: { title: string; description: string };

  hero: {
    eyebrow: string;
    h1: string;
    lead: string;
    ctaPrimary: string;
    ctaPrimaryHref: string;
    ctaSecondary: string;
    ctaSecondaryHref: string;
    image: {
      src: string;
      srcset: string;
      sizes: string;
      width: number;
      height: number;
      alt: string;
      href: string;
      mobileSrc: string;
      mobileSrcset: string;
    };
  };

  makeSection: {
    eyebrow: string;
    title: string;
    intro: string;
    allLinkLabel: string;
    allLinkHref: string;
    /** Optional per-card description override, keyed by the card's href.
     *  Only used to enrich a shared category label with locally relevant,
     *  repo-confirmed detail — never to invent a new card or URL. */
    categoryOverrides?: Record<string, string>;
  };

  localIntro: {
    eyebrow: string;
    title: string;
    paragraphs: string[];
    /** Commercial-proof checklist (NOT a numbered process — that lives in its
     *  own section). Confirmed facts only. */
    asideTitle: string;
    asideItems: string[];
  };

  scenarios: { eyebrow: string; title: string; intro: string; cards: CityHubScenario[] };

  projectsSection: {
    eyebrow: string;
    title: string;
    intro: string;
    viewAllLabel: string;
    viewAllHref: string;
    emptyText: string;
    gridAriaLabel: string;
  };

  processSection: { eyebrow: string; title: string; steps: [string, string][] };

  geography: {
    eyebrow: string;
    title: string;
    paragraphs: string[];
    asideTitle: string;
    /** Confirmed served areas only. */
    areas: string[];
    /** Administrative area name for the Service schema `areaServed`. */
    oblast: string;
  };

  cost: {
    eyebrow: string;
    title: string;
    intro: string;
    factors: [string, string][];
    ctaLabel: string;
    ctaHref: string;
  };

  why: {
    eyebrow: string;
    title: string;
    intro: string;
    aboutLabel: string;
    aboutHref: string;
    stats: [string, string][];
  };

  b2b: {
    eyebrow: string;
    title: string;
    intro: string;
    points: string[];
    ctaLabel: string;
    ctaHref: string;
  };

  contact: {
    eyebrow: string;
    title: string;
    intro: string;
    /** Action label for the phone button. */
    phoneLabel: string;
    /** The number itself, kept visible as small plain text. */
    phone: string;
    phoneHref: string;
    hours: string;
    telegramLabel: string;
    telegramHref: string;
    ctaLabel: string;
    ctaHref: string;
    officesLabel: string;
    officesHref: string;
  };

  faq: { title: string; intro: string; items: [string, string][] };

  knowledge: { eyebrow: string; title: string; intro: string; links: CityHubLink[] };

  finalCta: {
    eyebrow: string;
    title: string;
    intro: string;
    ctaPrimary: string;
    ctaPrimaryHref: string;
    ctaSecondary: string;
    ctaSecondaryHref: string;
  };
}


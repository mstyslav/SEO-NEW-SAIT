const byUk = new Map(INTL_ROUTES.map((route) => [route.uk, route]));
const byIntl = new Map(INTL_ROUTES.flatMap((route) => intlLocales.filter((locale) => route[locale]).map((locale) => [route[locale] as string, route] as const)));
const byId = new Map(INTL_ROUTES.map((route) => [route.id, route]));

export const isIntlLocale = (locale: string | undefined): locale is IntlLocale => intlLocales.includes(locale as IntlLocale);

/** The route entry of an international URL (exact path with trailing slash), if it is one. */
export const intlRouteOfPath = (pathname: string): IntlRoute | undefined => byIntl.get(pathname);

/** The route entry of a UA (unprefixed) path, if that page has international versions. */
export const intlRouteOfUk = (ukPath: string): IntlRoute | undefined => byUk.get(ukPath);

/** The UA fallback page of a German-only page (undefined for every page that has a UA original). */
export const intlDeOnlyFallback = (basePath: string): string | undefined => byUk.get(basePath)?.deOnlyFallback;

export const intlRouteById = (id: string): IntlRoute | undefined => byId.get(id);

/** Localized URL of a page by id — throws on a typo so a broken link can never be built. */
export const intlHref = (id: string, locale: IntlLocale, hash = ''): string => {
  const route = byId.get(id);
  if (!route?.[locale]) throw new Error(`No ${locale} version of international page: ${id}`);
  return `${route[locale]}${hash}`;
};

/**
 * Nearest UA ancestor of `ukPath` that has a version in `locale` (the page itself first), or the
 * localized home page. Used for links to UA-only pages from international pages.
 */
export const intlFallbackPath = (ukPath: string, locale: IntlLocale): string => {
  const parts = ukPath.split('/').filter(Boolean);
  for (let length = parts.length; length > 0; length -= 1) {
    const candidate = `/${parts.slice(0, length).join('/')}/`;
    const route = byUk.get(candidate);
    if (route?.[locale]) return route[locale] as string;
  }
  return `/${locale}/`;
};

/**
 * Build-time guard for the thin route files in src/pages/{en,de,es}/: the file's own URL must be the
 * URL the route map gives this page, so a renamed folder can never drift from hreflang/sitemap/links.
 */
export const assertIntlRoute = (pathname: string, id: string, locale: IntlLocale): void => {
  const expected = intlHref(id, locale);
  const actual = pathname.endsWith('/') ? pathname : `${pathname}/`;
  if (actual !== expected) throw new Error(`International route mismatch: ${actual} is not the ${locale} URL of "${id}" (${expected})`);
};

/** Last path segment of a page's localized URL (for getStaticPaths of the dynamic route files). */
export const intlSlug = (route: IntlRoute, locale: IntlLocale): string => (route[locale] ?? '').split('/').filter(Boolean).pop() ?? '';

/** Routes that have a version in `locale`. */
export const intlRoutesOf = (locale: IntlLocale): IntlRoute[] => INTL_ROUTES.filter((route) => route[locale]);

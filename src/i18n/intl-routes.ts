/**
 * EN / DE / ES language versions — the single source of truth for which international pages exist.
 *
 * Every entry maps one real UA page (unprefixed path) to its localized URL in each international
 * locale. International slugs are localized (not transliterated UA slugs), so the mapping is
 * explicit instead of the `/ru${path}` rule used for Russian.
 *
 * A UA page that is not listed here has no EN/DE/ES version on purpose (UA-only market pages,
 * configurators with UAH prices, the knowledge base, city pages, …). Links to such pages from an
 * international page fall back to the nearest listed parent (see localizedPath in ./helpers), never
 * to the UA page, so international pages only link to their own language.
 *
 * Adding a language version = add the entry here + its content in src/content/i18n/intl/*.
 * Pages are generated by src/pages/{en,de,es}/[...path].astro from this list; the sitemap,
 * hreflang, the language switcher and the localized links all read it.
 */
export const intlLocales = ['en', 'de', 'es'] as const;
export type IntlLocale = typeof intlLocales[number];

export type IntlPageKind = 'home' | 'about' | 'contacts' | 'hub' | 'child' | 'projects' | 'case' | 'legal';

export interface IntlRoute {
  /** Stable page id, used to look up the localized content. */
  id: string;
  kind: IntlPageKind;
  /** The UA (unprefixed) page this is a language version of. */
  uk: string;
  /** A locale a page does not (yet) have is left out: no hreflang, no sitemap entry, links fall back to the parent hub. */
  en?: string;
  de?: string;
  /** Set for pages that exist only in German: the nearest real UA page (language switcher target). */
  deOnlyFallback?: string;
  es?: string;
  /** Child pages: id of the parent hub (same locale). */
  parent?: string;
}

const page = (id: string, kind: IntlPageKind, uk: string, en: string, de: string, es: string): IntlRoute => ({
  id, kind, uk, en: `/en${en}`, de: `/de${de}`, es: `/es${es}`
});


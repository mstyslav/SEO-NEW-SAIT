// Generates src/data/contact-maps.ts: SVG outlines + marker positions for the Contacts page maps.
// Source: Natural Earth 1:10m Admin 0 Countries (public domain, https://www.naturalearthdata.com/about/terms-of-use/),
// "ukr" variant (Ukraine incl. Crimea). Usage: node scripts/generate-contact-maps.mjs <ne_10m_admin_0_countries_ukr.geojson>
// Projection (both maps): equirectangular scaled by cos(centre latitude): x = (lon - lonMin) * cos(latC) * k, y = (latMax - lat) * k.
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) throw new Error('Pass the path to ne_10m_admin_0_countries_ukr.geojson');
const world = JSON.parse(readFileSync(src, 'utf8'));
const W = 480, H = 300, PAD = 14;

const CITIES = {
  ukraine: [['kyiv', 50.4501, 30.5234], ['odesa', 46.4825, 30.7233], ['lviv', 49.8397, 24.0297]],
  austria: [['wien', 48.2082, 16.3738]]
};
const COUNTRIES = { ukraine: ['UKR', 0.012, 0.15], austria: ['AUT', 0.003, 0.002] }; // [ISO, simplify tolerance (deg), min polygon area (deg²)]

const ringArea = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0) / 2);
function simplify(pts, tol) {
  const keep = new Array(pts.length).fill(false); keep[0] = keep[pts.length - 1] = true;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const [x, y] = pts[i], [x1, y1] = pts[a], [x2, y2] = pts[b];
      const dx = x2 - x1, dy = y2 - y1, len = dx * dx + dy * dy;
      const t = len ? Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / len)) : 0;
      const d = Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = true; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const out = {};
for (const [key, [iso, tol, minArea]] of Object.entries(COUNTRIES)) {
  const feat = world.features.find((f) => f.properties.ADM0_A3 === iso);
  const polys = (feat.geometry.type === 'Polygon' ? [feat.geometry.coordinates] : feat.geometry.coordinates)
    .map((p) => p[0]).filter((r) => ringArea(r) >= minArea).map((r) => simplify(r, tol));
  const all = polys.flat();
  const lonMin = Math.min(...all.map((p) => p[0])), lonMax = Math.max(...all.map((p) => p[0]));
  const latMin = Math.min(...all.map((p) => p[1])), latMax = Math.max(...all.map((p) => p[1]));
  const cos = Math.cos(((latMin + latMax) / 2) * Math.PI / 180);
  const k = Math.min((W - 2 * PAD) / ((lonMax - lonMin) * cos), (H - 2 * PAD) / (latMax - latMin));
  const ox = (W - (lonMax - lonMin) * cos * k) / 2, oy = (H - (latMax - latMin) * k) / 2;
  const proj = (lon, lat) => [ox + (lon - lonMin) * cos * k, oy + (latMax - lat) * k];
  const f1 = (n) => Math.round(n * 10) / 10;
  const path = polys.map((r) => 'M' + r.map(([lo, la]) => proj(lo, la).map(f1).join(' ')).join('L') + 'Z').join('');
  const markers = Object.fromEntries(CITIES[key].map(([id, lat, lon]) => { const [x, y] = proj(lon, lat); return [id, { lat, lon, x: f1(x), y: f1(y) }]; }));
  out[key] = { path, markers };
}

const ts = `// GENERATED by scripts/generate-contact-maps.mjs — do not edit by hand.
// Geodata: Natural Earth 1:10m Admin 0 Countries (public domain; Ukraine in its internationally recognised borders incl. Crimea).
// Projection: x = (lon - lonMin) * cos(latC) * k + ox, y = (latMax - lat) * k + oy (same scale on both axes).
export const CONTACT_MAP_VIEWBOX = { width: ${W}, height: ${H} } as const;
export const CONTACT_MAPS = ${JSON.stringify(out, null, 2)} as const;
`;
writeFileSync(new URL('../src/data/contact-maps.ts', import.meta.url), ts);
console.log(Object.entries(out).map(([k, v]) => `${k}: path ${v.path.length} chars, markers ${JSON.stringify(v.markers)}`).join('\n'));
